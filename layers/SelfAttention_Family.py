class MyAttentionLayerV6(nn.Module):
    def __init__(self, d_model, n_heads, dropout, d_keys=None,
                 d_values=None):
        super(MyAttentionLayerV6, self).__init__()

        # 基础参数初始化
        d_keys = d_keys or (d_model // n_heads)
        d_values = d_values or (d_model // n_heads)
        self.dropout = nn.Dropout(dropout)

        # 保存外部注意力模块
        self.line_attention1 = nn.Linear(d_keys, d_keys)
        self.line_attention2 = nn.Linear(d_keys, d_keys)

        # 仅保留查询投影
        self.query_projection = nn.Linear(d_model, d_keys * n_heads)
        self.key_projection = nn.Linear(d_model, d_keys * n_heads)
        self.out_projection = nn.Linear(d_values * n_heads, d_model)
        self.n_heads = n_heads

        # 添加 LayerNorm 用于正则化输入
        self.layer_norm = nn.LayerNorm(d_model)
        self.layer_norm2 = nn.LayerNorm(d_keys)


    def forward(self, queries, keys, values, attn_mask, tau=None, delta=None):
        B, L, _ = queries.shape
        _, S, _ = keys.shape
        H = self.n_heads

        #对 queries 进行 LayerNorm 正则化
        x_norm = self.layer_norm(queries)  # [B, L, d_model]

        # 将正则化后的 x_norm 作为 K 和 V
        Q = x_norm  # [B, L, d_model]
        K = x_norm  # [B, L, d_model]
        V = x_norm

        # B L H N
        Q = self.dropout(self.query_projection(Q).view(B, L, H, -1))
        K = self.dropout(self.key_projection(K).view(B, S, H, -1))
        V = self.dropout(self.value_projection(V).view(B, S, H, -1))

        # 生成外部注意力权重 (形状: [B, L, H, d_model]
        Q = self.line_attention1(Q)  # [B, L, H, d_model]
        Q = self.layer_norm2(Q)
        Q = self.line_attention1(Q)  # [B, L, H, d_model]


        # 计算输出
        out = torch.einsum("blhd,bshd->blhd", Q, K)  # [B, L, H, d_values]


        V = torch.fft.rfft(V)
        V = nn.functional.dropout(V, p=0.1)

        out = torch.einsum("blhd,bshd->blhd", out, V)
        out = torch.fft.irfft(out)

        # 合并头并投影输出
        out = out.permute(0, 2, 1, 3).contiguous().view(B, L, -1)
        out = self.dropout(self.out_projection(out))

        # 返回输出和注意力权重
        return out,None

